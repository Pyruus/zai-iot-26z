CREATE TABLE admins (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    username character varying(50) NOT NULL,
    password_hash text NOT NULL,
    created_at timestamp with time zone NOT NULL,
    password_changed_at timestamp with time zone,
    CONSTRAINT pk_admins PRIMARY KEY (id)
);

CREATE TABLE event_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at timestamp with time zone NOT NULL,
    level character varying(10) NOT NULL,
    kind character varying(40) NOT NULL,
    series_id integer,
    sensor_id integer,
    message text NOT NULL,
    payload jsonb,
    CONSTRAINT pk_event_log PRIMARY KEY (id)
);

CREATE TABLE series (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name character varying(100) NOT NULL,
    min_value double precision NOT NULL,
    max_value double precision NOT NULL,
    color character(7) NOT NULL,
    icon character varying(30),
    unit character varying(20),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_series PRIMARY KEY (id),
    CONSTRAINT ck_series_color CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_series_name CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_series_range CHECK (min_value < max_value)
);

CREATE TABLE sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_id integer NOT NULL,
    token_hash character(64) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    revoked_at timestamp with time zone,
    CONSTRAINT pk_sessions PRIMARY KEY (id),
    CONSTRAINT fk_sessions_admins_admin_id FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE CASCADE
);

CREATE TABLE sensors (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name character varying(100) NOT NULL,
    series_id integer NOT NULL,
    api_key_hash character(64) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    revoked_at timestamp with time zone,
    last_measurement_at timestamp with time zone,
    CONSTRAINT pk_sensors PRIMARY KEY (id),
    CONSTRAINT fk_sensors_series_series_id FOREIGN KEY (series_id) REFERENCES series (id) ON DELETE CASCADE
);

CREATE TABLE measurements (
    id bigint GENERATED ALWAYS AS IDENTITY,
    ts timestamp with time zone NOT NULL,
    series_id integer NOT NULL,
    sensor_id integer,
    value double precision NOT NULL,
    received_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_measurements PRIMARY KEY (id, ts),
    CONSTRAINT fk_measurements_sensors_sensor_id FOREIGN KEY (sensor_id) REFERENCES sensors (id) ON DELETE SET NULL,
    CONSTRAINT fk_measurements_series_series_id FOREIGN KEY (series_id) REFERENCES series (id) ON DELETE CASCADE
);

